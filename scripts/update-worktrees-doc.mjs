#!/usr/bin/env node
// Regenerates docs/worktrees.md — the index CRUUSH-RULES J1 requires, so an
// agent picking up work knows what is where instead of asking.
//
//   node scripts/update-worktrees-doc.mjs
//   node scripts/update-worktrees-doc.mjs --check   # non-zero if stale
//
// Purpose text is preserved between runs: put it in the "Purpose" column and
// it survives regeneration (matched on branch name).

import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import process from 'node:process';

const ROOT = execFileSync('git', ['rev-parse', '--show-toplevel'], { encoding: 'utf8' }).trim();
const OUTPUT = path.join(ROOT, 'docs', 'worktrees.md');
const CHECK_ONLY = process.argv.includes('--check');

function git(args, cwd = ROOT) {
  try {
    return execFileSync('git', args, { cwd, encoding: 'utf8' }).trim();
  } catch {
    return '';
  }
}

function parseWorktrees() {
  const raw = git(['worktree', 'list', '--porcelain']);
  const entries = [];
  let current = null;
  for (const line of raw.split('\n')) {
    if (line.startsWith('worktree ')) {
      if (current) entries.push(current);
      current = { path: line.slice('worktree '.length) };
    } else if (line.startsWith('HEAD ')) {
      current.head = line.slice('HEAD '.length);
    } else if (line.startsWith('branch ')) {
      current.branch = line.slice('branch '.length).replace('refs/heads/', '');
    } else if (line === 'detached') {
      current.branch = '(detached)';
    }
  }
  if (current) entries.push(current);
  return entries;
}

function existingPurposes() {
  if (!existsSync(OUTPUT)) return new Map();
  const purposes = new Map();
  for (const line of readFileSync(OUTPUT, 'utf8').split('\n')) {
    const match = /^\|\s*`([^`]+)`\s*\|[^|]*\|[^|]*\|[^|]*\|[^|]*\|\s*([^|]*?)\s*\|/.exec(line);
    if (match) purposes.set(match[1], match[2].trim());
  }
  return purposes;
}

function describe(entry) {
  const branch = entry.branch ?? '(detached)';
  const shortSha = (entry.head ?? '').slice(0, 8);
  const lastCommit = git(['log', '-1', '--format=%cs %s', entry.head]) || '';
  const dirty = git(['status', '--porcelain'], entry.path);
  const counts = git(['rev-list', '--left-right', '--count', `origin/main...${entry.head}`]);
  const [behind, ahead] = counts ? counts.split(/\s+/) : ['?', '?'];
  return {
    branch,
    shortSha,
    date: lastCommit.slice(0, 10),
    subject: lastCommit.slice(11, 72),
    state: dirty ? `dirty (${dirty.split('\n').length} files)` : 'clean',
    ahead,
    behind,
    merged: ahead === '0' ? 'yes' : 'no',
    // Worktrees live outside the repo as often as inside it; a relative path
    // full of ../.. is unreadable, so only relativise when it stays inside.
    path: (() => {
      const relative = path.relative(ROOT, entry.path);
      if (!relative) return '.';
      return relative.startsWith('..') ? entry.path : relative;
    })(),
  };
}

git(['fetch', '--quiet', 'origin', 'main']);
const purposes = existingPurposes();
const rows = parseWorktrees().map(describe);

const body = `# Worktrees

Generated by \`node scripts/update-worktrees-doc.mjs\`. Regenerate it whenever you
create, merge, or abandon a worktree — CRUUSH-RULES J1.

The **Purpose** column is hand-written and survives regeneration. Fill it in when you
create a worktree so the next agent (or the next you) does not have to reverse-engineer
the branch name.

| Branch | Worktree path | Last commit | State | Ahead/behind main | Purpose |
| --- | --- | --- | --- | --- | --- |
${rows.map((row) => `| \`${row.branch}\` | \`${row.path}\` | ${row.date} ${row.shortSha} ${row.subject} | ${row.state} | +${row.ahead}/-${row.behind} | ${purposes.get(row.branch) ?? ''} |`).join('\n')}

## Rules that apply here

- **J1** — every worktree gets a row above.
- **J2** — when continuing another agent's work, read this table first and report what is
  where before touching anything.
- **J3** — never abandon uncommitted work. A row showing \`dirty\` with no owner is a
  liability; commit it as WIP with a message naming the next step.
- **J4** — never revert or overwrite work you did not create without saying so first.
`;

if (CHECK_ONLY) {
  const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8') : '';
  if (current.trim() !== body.trim()) {
    console.error('worktrees: docs/worktrees.md is stale. Run: node scripts/update-worktrees-doc.mjs');
    process.exit(1);
  }
  console.log('worktrees: docs/worktrees.md is current');
  process.exit(0);
}

writeFileSync(OUTPUT, body);
console.log(`worktrees: wrote ${path.relative(ROOT, OUTPUT)} (${rows.length} worktrees)`);
